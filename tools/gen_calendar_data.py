def jd_from_dt(dt):
    y=dt.year; m=dt.month
    d=dt.day+(dt.hour+dt.minute/60+dt.second/3600)/24
    if m<=2: y-=1; m+=12
    A=y//100; B=2-A+A//4
    return math.floor(365.25*(y+4716))+math.floor(30.6001*(m+1))+d+B-1524.5

def dt_from_jd(jd):
    jd+=0.5; Z=int(jd); F=jd-Z
    if Z<2299161: A=Z
    else:
        a=int((Z-1867216.25)/36524.25); A=Z+1+a-a//4
    B=A+1524; C=int((B-122.1)/365.25); D=int(365.25*C); E=int((B-D)/30.6001)
    day=B-D-int(30.6001*E)+F
    month=E-1 if E<14 else E-13
    year=C-4716 if month>2 else C-4715
    d=int(day); secs=int(round((day-d)*86400))
    return datetime.datetime(year,month,d)+datetime.timedelta(seconds=secs)

def sun_lon(jd):
    T=(jd-2451545.0)/36525.0
    L0=280.46646+36000.76983*T+0.0003032*T*T
    M=357.52911+35999.05029*T-0.0001537*T*T
    Mr=math.radians(M)
    C=(1.914602-0.004817*T-0.000014*T*T)*math.sin(Mr)+(0.019993-0.000101*T)*math.sin(2*Mr)+0.000289*math.sin(3*Mr)
    lam=L0+C-0.00569-0.00478*math.sin(math.radians(125.04-1934.136*T))
    return lam % 360.0

def term_day(year,k):
    target=(285+15*k)%360
    jd0=jd_from_dt(datetime.datetime(year,1,1))+k*15.22
    lo,hi=jd0-20,jd0+20
    for _ in range(60):
        mid=(lo+hi)/2
        if ((sun_lon(mid)-target+180)%360-180)>0: hi=mid
        else: lo=mid
    dt=dt_from_jd((lo+hi)/2)+datetime.timedelta(hours=8)   # Beijing time
    assert dt.month==k//2+1, (year,k,dt)
    return dt.day


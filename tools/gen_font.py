#!/usr/bin/env python3
"""Generate a 1bpp Unifont subset for the ESP32 local UI.

ASCII: 8x16, CJK: 16x16, packed MSB-left, 1 = ink.
Covers GB2312 level 1+2 and punctuation (common Simplified Chinese).
"""
from PIL import Image, ImageDraw, ImageFont
import os, sys

FONT_PATH = "/usr/share/fonts/OTF/unifont.otf"
OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "epaper42_web", "ui_font.h")
font = ImageFont.truetype(FONT_PATH, 16)

def glyph(ch, w, h=16):
    im = Image.new("1", (w, h), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), ch, font=font, fill=1)
    px = im.load()
    rows = []
    for y in range(h):
        if w == 8:
            b = 0
            for x in range(8):
                if px[x, y]: b |= 0x80 >> x
            rows.append(b)
        else:
            hi = lo = 0
            for x in range(16):
                if px[x, y]:
                    if x < 8: hi |= 0x80 >> x
                    else: lo |= 0x80 >> (x - 8)
            rows.append(hi); rows.append(lo)
    return rows

# ASCII printable
ascii_rows = []
for c in range(0x20, 0x7F):
    ascii_rows.append(glyph(chr(c), 8))

# GB2312: symbols/punctuation + level 1 + level 2
cps = set()
for hi in range(0xA1, 0xF8):
    for lo in range(0xA1, 0xFF):
        try:
            ch = bytes([hi, lo]).decode("gb2312")
        except UnicodeDecodeError:
            continue
        if len(ch) == 1:
            cps.add(ord(ch))
# extra common punctuation / arrows / symbols
for ch in "　，。！？：；、“”‘’（）《》【】—…·←↑→↓■□●○◆◇★☆":
    cps.add(ord(ch))
cps = sorted(cp for cp in cps if cp > 0x7F)

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by tools/gen_font.py from GNU Unifont 16px.\n")
    f.write("// GNU Unifont: GPLv2+ with font embedding exception. 1 = ink, MSB left.\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("struct UiGlyph { uint32_t cp; uint8_t bmp[32]; };\n\n")
    f.write("static const uint8_t UI_ASCII[95][16] = {\n")
    for i, rows in enumerate(ascii_rows):
        f.write("  {" + ",".join("0x%02X" % b for b in rows) + "}, // %r\n" % chr(0x20+i))
    f.write("};\n\n")
    f.write("static const UiGlyph UI_CJK[] = {\n")
    for cp in cps:
        rows = glyph(chr(cp), 16)
        f.write("  {0x%04X,{" % cp + ",".join("0x%02X" % b for b in rows) + "}},\n")
    f.write("};\n")
    f.write("static const uint16_t UI_CJK_COUNT = %d;\n" % len(cps))
print("wrote", OUT, "cjk", len(cps), "bytes", os.path.getsize(OUT))
